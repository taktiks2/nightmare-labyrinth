//! グローバル定数定義
//!
//! ゲーム全体で使用する定数値を定義
//! スプライトサイズ、ウィンドウサイズなどの設定

/// スプライトの基本サイズ（ピクセル）
///
/// ゲーム内の1タイルのサイズを表す
/// 32x32ピクセルのスプライトを使用
pub const SPRITE_SIZE: f32 = 32.;

/// スプライトの拡大率
///
/// スプライトの表示サイズを調整するためのスケール値
/// 1.0 = 元のサイズ
pub const SPRITE_SCALE: f32 = 1.;

/// ゲームウィンドウの幅（ピクセル）
///
/// 16:9のアスペクト比でHD解像度をベースとした幅
pub const WINDOW_WIDTH: f32 = 1280.;

/// ゲームウィンドウの高さ（ピクセル）
///
/// 16:9のアスペクト比でHD解像度をベースとした高さ
pub const WINDOW_HEIGHT: f32 = 720.;
